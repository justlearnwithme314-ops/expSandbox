"""Read-only inventory of the previous Godot project, for tracking port scope."""
import argparse
import json
from pathlib import Path

parser=argparse.ArgumentParser()
parser.add_argument("source",type=Path)
args=parser.parse_args()
source=args.source.resolve()
modules=[]
for manifest in sorted((source/"mods").glob("*/mod.json")):
    data=json.loads(manifest.read_text(encoding="utf-8-sig"))
    scripts=list(manifest.parent.rglob("*.gd"))
    modules.append(dict(folder=manifest.parent.name,id=data.get("id"),name=data.get("name"),version=data.get("version"),dependencies=data.get("dependencies",[]),scripts=len(scripts),lines=sum(len(p.read_text(encoding="utf-8-sig").splitlines()) for p in scripts),port_status="not assessed"))
out=Path(__file__).resolve().parents[1]/"docs/generated"
out.mkdir(parents=True,exist_ok=True)
(out/"godot_modules.json").write_text(json.dumps(dict(source=str(source),modules=modules),indent=2)+"\n",encoding="utf-8")
lines=["# Godot source module inventory","","Generated by `tools/audit_godot.py`. Source is read-only. Counts identify scope, not working feature parity.","","| Module | Manifest ID | GDScript files | Lines |","|---|---|---:|---:|"]
for m in modules: lines.append(f"| {m['folder']} | `{m['id']}` | {m['scripts']} | {m['lines']} |")
(out/"GODOT_MODULES.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
print(f"Inventoried {len(modules)} modules, {sum(m['scripts'] for m in modules)} scripts, {sum(m['lines'] for m in modules)} lines")
